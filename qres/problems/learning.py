# the quantum kernel
# --------------------------------------------------------------------------

def quantum_kernel_matrix(a: np.ndarray, b: np.ndarray, reps: int = 2, environment=None):
    """Fidelity kernel ``|<phi(x)|phi(y)>|^2`` from a ZZ feature map.

    Exact by statevector when ``environment`` is ``None``.  Under a device the
    standard estimator is the compute-uncompute circuit -- prepare ``phi(x)``,
    apply ``phi(y)^dagger``, measure the all-zeros probability -- whose gate
    count is what the budget has to accommodate, and it is returned alongside.
    """
    from qiskit.circuit.library import ZZFeatureMap
    from qiskit.quantum_info import Statevector

    features = a.shape[1]
    feature_map = ZZFeatureMap(feature_dimension=features, reps=reps)

    if environment is None:
        states_a = [Statevector(feature_map.assign_parameters(x)).data for x in a]
        states_b = [Statevector(feature_map.assign_parameters(y)).data for y in b]
        matrix = np.empty((len(a), len(b)))
        for i, sa in enumerate(states_a):
            for j, sb in enumerate(states_b):
                matrix[i, j] = abs(np.vdot(sa, sb)) ** 2
        return matrix, 0

    # Transpile ONCE.  The compute-uncompute circuit has the same structure for
    # every kernel entry -- only the parameters differ -- so transpiling inside
    # the loop repeats identical work 1 120 times on a 40-sample dataset.  This
    # is the pattern `ShotEstimator` already uses for the same reason.
    from qiskit.circuit import ParameterVector

    left = ParameterVector("l", features)
    right = ParameterVector("r", features)
    template = feature_map.assign_parameters(list(left)).compose(
        feature_map.assign_parameters(list(right)).inverse()
    )
    template.measure_all()
    isa = environment.prepare(template, optimization_level=1)
    gates = sum(
        n for gate, n in isa.count_ops().items()
        if gate in {"cx", "cz", "ecr", "cy", "swap", "rzz"}
    )

    zeros = "0" * features
    matrix = np.empty((len(a), len(b)))
    circuits, index = [], []
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            circuits.append(isa.assign_parameters(np.concatenate([x, y])))
            index.append((i, j))

    # and run them in batches rather than one call per entry
    batch = 256
    for start in range(0, len(circuits), batch):
        chunk = circuits[start : start + batch]
        results = environment.run(chunk, 2048)
        if not isinstance(results, list):
            results = [results]
        for (i, j), counts in zip(index[start : start + batch], results):
            matrix[i, j] = counts.get(zeros, 0) / sum(counts.values())

    return matrix, gates


def quantum_kernel_accuracy(dataset: Dataset, reps: int = 2, environment=None,
                            ridges=(1e-4, 1e-3, 1e-2, 1e-1)) -> dict:
    """Best test accuracy from the quantum kernel, same ridge grid as classical."""
    started = time.perf_counter()
    train_kernel, gates = quantum_kernel_matrix(
        dataset.train_x, dataset.train_x, reps, environment
    )
    test_kernel, _ = quantum_kernel_matrix(
        dataset.test_x, dataset.train_x, reps, environment
    )

    best = 0.0
    for ridge in ridges:
        predicted = kernel_ridge_classify(train_kernel, dataset.train_y, test_kernel, ridge)
        best = max(best, float(np.mean(predicted == dataset.test_y)))

    return {
        "accuracy": best,
        "two_qubit_gates_per_entry": gates,
        "kernel_entries": len(dataset.train_x) ** 2 + len(dataset.test_x) * len(dataset.train_x),
        "seconds": time.perf_counter() - started,
    }
